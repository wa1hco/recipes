def cjk_count(s: str) -> int:
    return sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")


def translate_title(zh: str) -> str:
    raw = zh.strip()
    raw = re.sub(r"\s*[|｜]\s*老[飯饭]骨\s*$", "", raw)
    key = re.sub(r"[～~\s]+$", "", raw)
    if key in UNPARSED:
        return UNPARSED[key]
    # loose match unparsed
    for k, v in UNPARSED.items():
        if raw.startswith(k[:12]):
            return v

    m = re.match(r"【([^】•]+)•([^】]+)】(.*)", raw)
    if m:
        prefix, dish, tag = m.group(1).strip(), m.group(2).strip(), m.group(3).strip(" ～~")
        pre = PREFIX.get(prefix, prefix)
        d = DISH.get(dish) or DISH.get(dish.replace("麵", "面")) or dish
        tag = re.sub(r"\s*[|｜]\s*老[飯饭]骨\s*$", "", tag).strip(" ～~")
        if tag and cjk_count(tag) < 4:
            return f"{pre} · {d} — {tag}" if tag else f"{pre} · {d}"
        return f"{pre} · {d}"
    m = re.match(r"【([^】]+)】(.*)", raw)
    if m:
        dish = m.group(1).strip()
        d = DISH.get(dish, dish)
        return d
    if cjk_count(raw) == 0:
        return raw
    return raw


def main() -> None:
    src = ROOT / "catalog.csv"
    rows = list(csv.DictReader(src.open(encoding="utf-8")))
    missing = []
    for r in rows:
        t = r["title"]
        m = re.match(r"【([^】•]+)•([^】]+)】", t)
        if m:
            dish = m.group(2).strip()
            if dish not in DISH and dish.replace("麵", "面") not in DISH:
                missing.append(dish)
    if missing:
        uniq = sorted(set(missing))
        print("MISSING DISHES", len(uniq))
        for d in uniq:
            print(" ", d)

    out_rows = []
    for r in rows:
        en = translate_title(r["title"])
        out_rows.append({**r, "title_en": en, "title_zh": r["title"]})

    csv_path = ROOT / "catalog-en.csv"
