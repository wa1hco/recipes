        w = csv.DictWriter(
            f,
            fieldnames=["category", "date", "duration", "id", "title_en", "title_zh", "subtitles", "url"],
        )
        w.writeheader()
        for r in out_rows:
            w.writerow({k: r[k] for k in w.fieldnames})

